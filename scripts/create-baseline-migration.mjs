#!/usr/bin/env node
/**
 * Creates the initial ("baseline") Prisma migration from prisma/schema.prisma using the
 * real Prisma CLI: `prisma migrate diff --from-empty --to-schema-datamodel ... --script`.
 * It needs no database connection. It refuses to run if migrations already exist, so it
 * can never overwrite or duplicate history. Run it once, review the SQL, and commit it.
 *
 *   npm run db:baseline
 */
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export function baselineTimestamp(date = new Date()) {
  const p = (n) => String(n).padStart(2, '0');
  return `${date.getUTCFullYear()}${p(date.getUTCMonth() + 1)}${p(date.getUTCDate())}${p(date.getUTCHours())}${p(date.getUTCMinutes())}${p(date.getUTCSeconds())}`;
}

export const LOCK_FILE_CONTENT = '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "mysql"\n';

/** Throws when any migration already exists. */
export function planBaseline(migrationsDir, now = new Date()) {
  if (fs.existsSync(migrationsDir)) {
    const existing = fs.readdirSync(migrationsDir, { withFileTypes: true }).filter((entry) => entry.isDirectory());
    if (existing.length > 0) {
      throw new Error(`Refusing to create a baseline: ${existing.length} migration(s) already exist in ${migrationsDir}.`);
    }
  }
  const dir = path.join(migrationsDir, `${baselineTimestamp(now)}_init`);
  return { dir, sqlPath: path.join(dir, 'migration.sql'), lockPath: path.join(migrationsDir, 'migration_lock.toml') };
}

function main() {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const schema = path.join(root, 'apps/api/prisma/schema.prisma');
  const plan = planBaseline(path.join(root, 'apps/api/prisma/migrations'));

  const npx = process.platform === 'win32' ? 'npx.cmd' : 'npx';
  const result = spawnSync(npx, ['prisma', 'migrate', 'diff', '--from-empty', '--to-schema-datamodel', schema, '--script'], {
    cwd: root,
    encoding: 'utf8',
    shell: process.platform === 'win32',
  });
  if (result.status !== 0 || !/CREATE TABLE/i.test(result.stdout)) {
    console.error(result.stderr || 'prisma migrate diff did not produce any CREATE TABLE statements');
    process.exit(1);
  }
  fs.mkdirSync(plan.dir, { recursive: true });
  fs.writeFileSync(plan.sqlPath, result.stdout);
  fs.writeFileSync(plan.lockPath, LOCK_FILE_CONTENT);
  console.log(`Created ${path.relative(root, plan.sqlPath)} (${(result.stdout.match(/CREATE TABLE/gi) || []).length} tables).`);
  console.log('Review the SQL, then commit apps/api/prisma/migrations/.');
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) main();
